// Regenerates the website's copy of the app's data. Run from the repo root with the path of a
// LunAR checkout:  node scripts/build-data.mjs ../LunAR
//
// - src/catalog.js: every catalog feature's ranking fields (the ranker needs all 40 to rank the
//   way the app does), but names, stories and photos only for the free sights. Pro sights ship
//   as anonymous numbers, so the website never shows Pro content.
// - assets/data/cities.json: cities of 100,000 people or more, with their time zones.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { cityMapping } from 'city-timezones'

const lunar = process.argv[2]
if (!lunar) throw new Error('usage: node scripts/build-data.mjs <path to LunAR checkout>')

const catalog = JSON.parse(readFileSync(join(lunar, 'ios/Moonbound/Catalog/en.lproj/FeatureCatalog.json'), 'utf8'))

// ProLock.isFree: binocular-easy, and not a limb sea.
const isFree = (f) => f.difficulty === 'binoculars' && !f.isLimbFeature
const rankingFields = ['id', 'difficulty', 'latitude', 'longitude', 'sunriseColongitude', 'sunsetColongitude',
  'isRaySystem', 'isLimbFeature', 'showpieceScore', 'isBestAtFullMoon']

const features = catalog.map((f) => {
  const entry = Object.fromEntries(rankingFields.map((k) => [k, f[k]]))
  if (isFree(f)) Object.assign(entry, { free: true, slug: f.slug, name: f.name, kind: f.kind, story: f.story })
  return entry
})

writeFileSync('src/catalog.js',
  '// Generated by scripts/build-data.mjs from the app\'s FeatureCatalog.json. Do not edit.\n' +
  `export default ${JSON.stringify(features, null, 1)}\n`)

const cities = cityMapping
  .filter((c) => c.pop >= 100000)
  .sort((a, b) => b.pop - a.pop)
  .map((c) => [c.city, c.country, +c.lat.toFixed(3), +c.lng.toFixed(3), c.timezone, c.pop])
mkdirSync('assets/data', { recursive: true })
writeFileSync('assets/data/cities.json', JSON.stringify(cities))

console.log(`${features.filter((f) => f.free).length} free sights of ${features.length}; ${cities.length} cities`)
